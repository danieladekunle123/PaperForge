// Builds THIRD_PARTY_NOTICES.md from the licence files of what actually ships, so it cannot drift.
// Usage: npm run notices
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))

// Bundled into the renderer or main process.
const NPM_PACKAGES = ['react', 'react-dom', 'scheduler', 'zustand', 'zod', '@tanstack/react-virtual', '@tanstack/virtual-core', 'lucide-react', 'pdfjs-dist', 'electron']
// Frozen into the worker.
const PYTHON_PACKAGES = ['pymupdf', 'pillow', 'pyinstaller']

function licenseText(directory) {
  const names = readdirSync(directory).filter((name) => /^(licen[cs]e|copying|notice)/i.test(name))
  return names.map((name) => readFileSync(join(directory, name), 'utf8').trim()).join('\n\n')
}

const out = []
out.push(`# Third-party notices

PaperForge is licensed under the GNU Affero General Public License, version 3 or later (see LICENSE).
The application redistributes the components below. This file is generated by \`npm run notices\` from
the licence files in the installed packages.

## Why PaperForge is AGPL

PaperForge bundles **PyMuPDF** and **MuPDF** from Artifex Software. They are available under the GNU AGPL
3.0 or a commercial licence from Artifex. PaperForge uses the AGPL option, so distributions of PaperForge
must offer the corresponding source of the whole application under the AGPL. A proprietary fork would need
a commercial licence from Artifex: https://artifex.com/licensing

MuPDF statically includes further open-source libraries, among them FreeType, HarfBuzz, lcms2, OpenJPEG,
jbig2dec, libjpeg, zlib and Gumbo. See the PyMuPDF distribution and https://mupdf.com/ for their terms.

## Summary

| Component | Version | Licence | Used for |
|---|---|---|---|`)

const uses = {
  react: 'User interface',
  'react-dom': 'User interface',
  scheduler: 'React dependency',
  zustand: 'State management',
  zod: 'Request validation',
  '@tanstack/react-virtual': 'Virtualised page grids',
  '@tanstack/virtual-core': 'Virtualised page grids',
  'lucide-react': 'Icons',
  'pdfjs-dist': 'Page previews and thumbnails (includes cmaps, standard fonts, WASM decoders)',
  electron: 'Desktop shell, includes Chromium and Node.js',
  pymupdf: 'PDF processing, includes MuPDF',
  pillow: 'Image processing',
  pyinstaller: 'Freezes the worker. Its bootloader ships inside the worker executable'
}

const bodies = []

for (const name of NPM_PACKAGES) {
  const directory = join(root, 'node_modules', name)
  const pkg = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'))
  out.push(`| ${name} | ${pkg.version} | ${pkg.license} | ${uses[name]} |`)
  bodies.push(`### ${name} ${pkg.version}\n\n\`\`\`\n${licenseText(directory) || `Licensed under ${pkg.license}.`}\n\`\`\``)
}

const sitePackages = join(root, 'worker', '.venv', 'Lib', 'site-packages')
for (const name of PYTHON_PACKAGES) {
  const info = readdirSync(sitePackages).find((entry) => entry.toLowerCase().startsWith(`${name}-`) && entry.endsWith('.dist-info'))
  if (!info) throw new Error(`Python package ${name} is not installed. Run "npm run setup".`)
  const version = info.slice(name.length + 1, -'.dist-info'.length)
  const metadata = readFileSync(join(sitePackages, info, 'METADATA'), 'utf8')
  const license = /^License-Expression: (.+)$/m.exec(metadata)?.[1] ?? /^License: (.+)$/m.exec(metadata)?.[1] ?? 'See below'
  out.push(`| ${name} | ${version} | ${license.slice(0, 80)} | ${uses[name]} |`)
  if (name === 'pymupdf') {
    bodies.push(`### pymupdf ${version}\n\nDual licensed under the GNU AGPL 3.0 (full text in LICENSE) or an Artifex commercial licence.`)
    continue
  }
  const licenseDir = [join(sitePackages, info, 'licenses'), join(sitePackages, info)].find((dir) => existsSync(dir) && licenseText(dir))
  bodies.push(`### ${name} ${version}\n\n\`\`\`\n${licenseDir ? licenseText(licenseDir) : license}\n\`\`\``)
}

out.push(`
Electron installers also include Chromium's own licence file (LICENSES.chromium.html) next to the executable.

## Licence texts

${bodies.join('\n\n')}
`)

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'), 'utf8')
console.log('Wrote THIRD_PARTY_NOTICES.md')
